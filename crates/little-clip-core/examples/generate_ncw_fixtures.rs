//! Regenerate owned NCW fixtures using the reviewed native library's encoder.
use std::{f64::consts::TAU, path::Path};

fn write(path: &Path, samples: &[i32], channels: u16, rate: u32) {
    let bytes = ncw::encode_pcm(
        samples,
        ncw::PcmSpec {
            channels,
            bits_per_sample: 16,
            sample_rate: rate,
        },
        ncw::StereoMode::Direct,
    )
    .unwrap();
    std::fs::write(path, bytes).unwrap();
}
fn main() {
    let fixtures = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures");
    for (name, channels, rate, seconds) in [("tones", 2, 44100, 4), ("mono", 1, 22050, 2)] {
        let mut values = Vec::new();
        for frame in 0..rate * seconds {
            for channel in 0..channels {
                let phase = frame as f64 * TAU * (440.0 + channel as f64 * 220.0) / rate as f64;
                values.push((phase.sin() * 0.65 * 32767.0).round() as i32);
            }
        }
        write(
            &fixtures.join(format!("audio/{name}.ncw")),
            &values,
            channels,
            rate,
        );
    }
    for name in ["soft", "bright"] {
        // The owned WAV fixtures are generated by scripts/multisample_fixture.py
        // with a conventional 44-byte PCM16 header, rather than arbitrary inputs.
        let wave = std::fs::read(fixtures.join(format!("multisample/{name}.wav"))).unwrap();
        assert_eq!(&wave[..4], b"RIFF");
        assert_eq!(&wave[36..40], b"data");
        let values: Vec<i32> = wave[44..]
            .as_chunks::<2>()
            .0
            .iter()
            .map(|b| i32::from(i16::from_le_bytes(*b)))
            .collect();
        write(
            &fixtures.join(format!("multisample/{name}.ncw")),
            &values,
            1,
            22050,
        );
    }
}
