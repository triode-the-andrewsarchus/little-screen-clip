//! PEAK CAN TRC File Format, versions 1.0–3.0.
//!
//! https://www.peak-system.com/produktcd/Pdf/English/PEAK_CAN_TRC_File_Format.pdf

use super::{
    super::{Channel, Direction, Frame, FrameKind, Identifier, MAX_FRAME_BYTES, dlc_bytes},
    data_bytes, decimal_ns, radix_value,
};

#[derive(Debug)]
pub(super) enum Trc {
    Legacy(u8),
    Modern { columns: Vec<u8> },
}

impl Trc {
    pub(super) fn recognize(text: &str) -> Option<Self> {
        let mut version = None;
        let mut start = false;
        let mut old_peak = false;
        let mut columns = None;
        let mut has_data = false;
        for line in text.lines().take(96) {
            let line = line.trim();
            if let Some(comment) = line.strip_prefix(';').map(str::trim) {
                if let Some(value) = comment.strip_prefix("$FILEVERSION=") {
                    version = Some(match value.trim() {
                        "1.0" => 10,
                        "1.1" => 11,
                        "1.2" => 12,
                        "1.3" => 13,
                        "2.0" => 20,
                        "2.1" => 21,
                        "3.0" => 30,
                        _ => return None,
                    });
                }
                if let Some(value) = comment.strip_prefix("$STARTTIME=") {
                    start = value.trim().parse::<f64>().is_ok_and(f64::is_finite);
                }
                if let Some(value) = comment.strip_prefix("$COLUMNS=") {
                    columns = parse_columns(value);
                }
                if comment.starts_with("PCAN-Net:")
                    || comment.contains("Generated by PCAN")
                    || comment.contains("Generated by PEAK")
                {
                    old_peak = true;
                }
            } else if !line.is_empty() {
                has_data = legacy(10, line, false).is_some();
                break;
            }
        }
        match version {
            Some(version @ 10..=13) if start || old_peak => Some(Self::Legacy(version)),
            Some(20 | 21 | 30) if start || old_peak => {
                columns.map(|columns| Self::Modern { columns })
            }
            None if old_peak && has_data => Some(Self::Legacy(10)),
            _ => None,
        }
    }

    pub(super) fn parse(&self, line: &str, bytes: bool) -> Option<Frame> {
        match self {
            Self::Legacy(version) => legacy(*version, line, bytes),
            Self::Modern { columns } => modern(columns, line, bytes),
        }
    }
}

fn parse_columns(value: &str) -> Option<Vec<u8>> {
    let columns: Vec<u8> = value
        .split(',')
        .map(|field| {
            let &[byte] = field.trim().as_bytes() else {
                return None;
            };
            b"NOTBIdRVSArslLD".contains(&byte).then_some(byte)
        })
        .collect::<Option<_>>()?;
    if columns.len() > 16
        || columns.last() != Some(&b'D')
        || !b"OTId".iter().all(|field| columns.contains(field))
        || !b"lL".iter().any(|field| columns.contains(field))
    {
        return None;
    }
    Some(columns)
}

fn legacy(version: u8, line: &str, bytes: bool) -> Option<Frame> {
    let mut words = line.split_ascii_whitespace();
    words.next()?.strip_suffix(')')?.parse::<u64>().ok()?;
    let time = decimal_ns(words.next()?, 6)?;
    let channel = if version >= 12 {
        Channel::Number(words.next()?.parse::<u16>().ok()?)
    } else {
        Channel::Number(1)
    };
    let direction = if version >= 11 { words.next()? } else { "" };
    let id = words.next()?;
    if version == 13 {
        words.next()?;
    }
    let dlc = words.next()?.parse::<u16>().ok()?;
    let mut words = words.peekable();
    let kind = match (direction, id, words.peek().copied()) {
        ("Error", _, _) | (_, _, Some("ERROR")) => FrameKind::Error,
        ("Warng", _, _) | (_, "FFFFFFFF", _) => FrameKind::Status,
        (_, _, Some("RTR")) => FrameKind::Remote,
        (_, _, _) if dlc > 8 && version == 13 => FrameKind::J1939,
        _ => FrameKind::Classic,
    };
    let mut frame = Frame::new(time, channel, kind);
    frame.direction = Direction::parse(direction);
    frame.dlc = Some(dlc);
    if !matches!(kind, FrameKind::Status | FrameKind::Error) {
        frame.id = Some(identifier(id)?);
    }
    if kind != FrameKind::Remote {
        if words.peek() == Some(&"ERROR") {
            words.next();
        }
        if dlc as usize > MAX_FRAME_BYTES {
            return None;
        }
        frame.data_len = dlc;
        frame.data = data_bytes(words, 16, dlc, bytes)?;
    }
    Some(frame)
}

fn modern(columns: &[u8], line: &str, bytes: bool) -> Option<Frame> {
    let mut words = line.split_ascii_whitespace();
    let mut time = None;
    let mut channel = Channel::Number(1);
    let mut id = None;
    let mut direction = Direction::Unknown;
    let mut length = None;
    let mut dlc = None;
    let mut kind = None;
    for (index, &column) in columns.iter().enumerate() {
        if column == b'D' {
            break;
        }
        if matches!(kind, Some(FrameKind::Error | FrameKind::Status)) {
            // These rows leave the ID, direction and length columns blank.
            return modern_event(time?, kind?, &columns[index..], words, bytes);
        }
        let word = words.next()?;
        match column {
            b'O' => time = decimal_ns(word, 6),
            b'T' => kind = Some(frame_kind(word)?),
            b'B' => channel = channel_value(word),
            b'I' => id = identifier(word),
            b'd' => direction = Direction::parse(word),
            b'l' => length = word.parse::<u16>().ok(),
            b'L' => dlc = word.parse::<u16>().ok(),
            _ => {}
        }
    }
    let mut kind = kind?;
    let mut frame = Frame::new(time?, channel, kind);
    frame.id = Some(id?);
    frame.direction = direction;
    frame.dlc = dlc;
    if kind != FrameKind::Remote {
        let length = length.or_else(|| {
            let code = dlc?;
            match kind {
                FrameKind::CanXl => code.checked_add(1),
                FrameKind::Flexible { .. } => dlc_bytes(code),
                _ => Some(code),
            }
        })?;
        if usize::from(length) > MAX_FRAME_BYTES {
            return None;
        }
        if kind == FrameKind::Classic && length > 8 {
            kind = FrameKind::J1939;
        }
        frame.kind = kind;
        frame.data_len = length;
        frame.data = data_bytes(words, 16, length, bytes)?;
    }
    Some(frame)
}

fn modern_event<'a>(
    time: i128,
    kind: FrameKind,
    columns: &[u8],
    mut words: impl Iterator<Item = &'a str>,
    bytes: bool,
) -> Option<Frame> {
    let channel = if columns.first() == Some(&b'B') {
        channel_value(words.next()?)
    } else {
        Channel::Number(1)
    };
    let mut frame = Frame::new(time, channel, kind);
    for word in words.take(24) {
        if word.len() == 2
            && let Some(byte) = radix_value(word, 16).and_then(|value| u8::try_from(value).ok())
        {
            frame.data_len += 1;
            if bytes {
                frame.data.push(byte);
            }
        }
    }
    Some(frame)
}

fn frame_kind(kind: &str) -> Option<FrameKind> {
    Some(match kind {
        "DT" => FrameKind::Classic,
        "FD" | "FB" | "FE" | "BI" => FrameKind::Flexible {
            bitrate_switch: matches!(kind, "FB" | "BI"),
            error_state: matches!(kind, "FE" | "BI"),
        },
        "XL" => FrameKind::CanXl,
        "RR" => FrameKind::Remote,
        "ER" | "EN" | "OF" | "PE" => FrameKind::Error,
        "ST" | "EC" => FrameKind::Status,
        _ => return None,
    })
}

fn channel_value(word: &str) -> Channel {
    word.parse().map_or(Channel::Unknown, Channel::Number)
}

fn identifier(word: &str) -> Option<Identifier> {
    let value = radix_value(word, 16)?;
    Identifier::new(
        value,
        word.trim_start_matches("0x").len() > 4 || value > 0x7ff,
    )
}
