from ui_acceptance_fixtures import pdf_fixture
import ui_acceptance_capture as private


def exercise_pdf_policy(session, root, binary):
    session.observe("initial", ["Spacing.pdf", "Untouched.txt"])
    sources = {p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in root.iterdir()}
    index = Path(session.env["XDG_DATA_HOME"]) / "little-screen-clip/search/index.sqlite"
    assert not index.exists()
    link_installed_inference(index)
    session.click(993, 118)
    session.key("Escape")
    generation, paths, count = inventory(index)
    assert len(paths) == 2 and count == 4, (paths, count)
    with sqlite3.connect(index) as db:
        parts = db.execute("SELECT s.modality,s.location,s.vector FROM segments s JOIN paths p ON p.file_id=s.file_id WHERE p.path=? ORDER BY s.id", [str(root/"Spacing.pdf").encode()]).fetchall()
        assert [(m,loc.split(' · ')[0]) for m,loc,_ in parts] == [('text','page 1'),('image','page 1'),('text','page 2')], [(m,loc) for m,loc,_ in parts]
        before = {loc:hashlib.sha256(vector).hexdigest() for m,loc,vector in parts if m == 'text'}
        untouched = db.execute("SELECT s.vector FROM segments s JOIN paths p ON p.file_id=s.file_id WHERE p.path=?", [str(root/"Untouched.txt").encode()]).fetchone()[0]
    session.click(993, 118)
    session.observe("new-pdf-policy", ["2 files", "4 vectors"])
    session.key("Escape")
    session.close()
    # Recreate the prior catalog's representation and text-only page decision,
    # preserving real canonical text vectors generated by this application.
    with sqlite3.connect(index) as db:
        file, representation = db.execute("SELECT f.id,f.format FROM files f JOIN paths p ON p.file_id=f.id WHERE p.path=?", [str(root/"Spacing.pdf").encode()]).fetchone()
        suffix = b'\0pdf-nonwhitespace-v2'
        assert representation.endswith(suffix)
        legacy = representation[:-len(suffix)]
        db.execute("DELETE FROM segments WHERE file_id=? AND modality='image'", [file])
        db.execute("UPDATE files SET format=? WHERE id=?", [legacy,file])
        db.execute("UPDATE source_digests SET format=? WHERE file_id=?", [legacy,file])
    session.process = session.children.start("files-resumed", [str(binary.resolve()), str(root)],
        env=session.env, cwd=session.output/"scratch", log_path=session.output/"files-resumed.log")
    private.wait_for_app_window(session.niri, session.env, session.process, session.output)
    session.key("F24")
    resumed, paths, count = inventory(index, generation)
    assert resumed > generation and len(paths) == 2 and count == 4
    with sqlite3.connect(index) as db:
        after = {loc:hashlib.sha256(vector).hexdigest() for loc,vector in db.execute("SELECT s.location,s.vector FROM segments s JOIN paths p ON p.file_id=s.file_id WHERE p.path=? AND s.modality='text'", [str(root/"Spacing.pdf").encode()])}
        assert after == before
        assert db.execute("SELECT s.vector FROM segments s JOIN paths p ON p.file_id=s.file_id WHERE p.path=?", [str(root/"Untouched.txt").encode()]).fetchone()[0] == untouched
    session.click(993, 118)
    session.observe("legacy-pdf-repaired", ["2 files", "4 vectors", "1 generated", "2 reused"])
    assert sources == {p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in root.iterdir()}
    (session.output/"pdf-policy-checks.json").write_text(json.dumps(dict(
        source_sha256=sources, text_vector_sha256=after,
        initial_generation=generation, resumed_generation=resumed,
        sparse_page_visual_segment_added=True, dense_page_stays_text_only=True,
        canonical_text_vectors_preserved=True, unrelated_text_not_reembedded=True,
        source_bytes_unchanged=True), indent=2))


def write_package(path, parts):
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, text in parts.items():
            archive.writestr(name, text)


def exercise(session, root):
    session.observe("initial", ["Annual.docx"])
    index = Path(session.env["XDG_DATA_HOME"]) / "little-screen-clip/search/index.sqlite"
    assert not index.exists()
    submit(session, ':content:"violet lighthouse"')
    session.observe("document-content", ["10 matching entries", "Annual.docx"])
    assert not index.exists(), "Literal document search must not create a semantic index"
    assert not index.parent.joinpath("runtime").exists()
    assert not index.parent.joinpath("models").exists()
    session.key("Escape")
    submit(session, ':content:"external secret must not appear"')
    session.observe("entities-not-resolved", ["0 matching entries", "unsupported/incomplete reads"])
    session.key("Escape")
    for name in ["Unsupported-image.png", "Unsupported-audio.wav", "Unsupported-video.mp4"]:
        (root / name).unlink()
    (root / "Unsafe.docx").rename(session.output / "Unsafe.docx")
    session.observe("before-enrollment", ["Annual.docx"])
    # Literal extraction must work before any inference installation exists.
    # Link the already installed test weights only for explicit enrollment.
    link_installed_inference(index)
    session.click(993, 118)
    session.key("Escape")
    _, paths, vectors = inventory(index)
    assert len(paths) == 11 and vectors == 14, (paths, vectors)
    with sqlite3.connect(index) as db:
        locations = [location for location, in db.execute("SELECT location FROM segments")]
        text = "\n".join(text for text, in db.execute("SELECT text FROM segments"))
        assert any(location.startswith("slide 1") for location in locations), locations
        assert any(location.startswith("sheet Data") for location in locations), locations
        assert "external secret must not appear" not in text
        assert "network-script-marker" not in text
        assert "violet lighthouse" in text
        for name, complete in [("Letter.rtf", True), ("Limited.rtf", False)]:
            parts = db.execute("SELECT s.modality,s.location,s.text,f.coverage FROM segments s JOIN files f ON f.id=s.file_id JOIN paths p ON p.file_id=f.id WHERE p.path=?", [str(root / name).encode()]).fetchall()
            assert len(parts) == 1, (name, parts)
            modality, location, body, coverage = parts[0]
            assert modality == "text" and location.startswith("RTF body text"), parts
            assert "violet lighthouse" in body and (coverage == "complete") == complete, parts
        assert db.execute("PRAGMA user_version").fetchone()[0] == 6
        assert db.execute("SELECT s.modality,count(*) FROM segments s JOIN paths p ON p.file_id=s.file_id WHERE p.path=? GROUP BY s.modality ORDER BY s.modality", [str(root / "Sparse.pdf").encode()]).fetchall() == [("image", 2), ("text", 2)]
    submit(session, ':content:"violet lighthouse"')
    session.observe("indexed-document-content", ["10 matching entries", "indexed text reused: 10 files", "Annual.docx"])
    session.key("Escape")
    submit(session, ':*.pdf;content:"Acceptance page"')
    session.observe("indexed-visual-document-content", ["1 matching entries", "indexed text reused: 1 file", "partial: indexed text only", "Sparse.pdf"])
    session.key("Escape")
    submit(session, ':emb:"violet lighthouse on a rocky coast"')
    session.observe("document-semantic", ["10 matching entries", "Semantic candidates", "Annual.docx"])
    session.key("Escape")
    pause_indexing(session, True, "pause-for-literal-edit")
    (root / "Source.rs").write_text("A newly changed marker is searchable without rebuilding the index.")
    submit(session, ':content:"violet lighthouse"')
    text = session.observe("old-literal-after-edit", ["9 matching entries", "Annual.docx"])
    assert "Source.rs" not in text, "Cached text from a replaced revision must not match"
    session.key("Escape")
    submit(session, ':content:"newly changed marker"')
    session.observe("fresh-literal-after-edit", ["1 matching entries", "Source.rs"])


def main():
    repository = Path(__file__).resolve().parent.parent
    args = application_arguments(__doc__, repository / "target/debug/clip-file-manager", lambda parser: parser.add_argument("--pdf-spacing", action="store_true"))
    output, root = media_fixture_directory(args)
    if args.pdf_spacing:
        pdf_fixture(root, 2, "Spacing.pdf", page_streams=[b'BT /F1 1 Tf 5 140 Td ('+b'A'*n+b') Tj 170 0 Td (B) Tj ET' for n in [198,199]])
        (root/"Untouched.txt").write_text("An ordinary text document about a mountain trail.")
        return run_application_acceptance(args, output, root, lambda session, root: exercise_pdf_policy(session, root, args.binary),
            "PDF sparse/dense whitespace boundary, retained lexical text, legacy representation repair without reembedding unrelated text")
    phrase = "The violet lighthouse stands on a rocky coast."
    write_package(root / "Annual.docx", {"word/document.xml": f'<w:document xmlns:w="word"><w:p><w:r><w:t>{phrase}</w:t></w:r></w:p></w:document>'})
    write_package(root / "Notes.odt", {"content.xml": f'<document xmlns:t="text"><t:p>{phrase}</t:p></document>'})
    write_package(root / "Slides.pptx", {
        "ppt/presentation.xml": '<presentation xmlns:r="relations"><sldId r:id="slide"/></presentation>',
        "ppt/_rels/presentation.xml.rels": '<Relationships><Relationship Id="slide" Target="slides/slide1.xml"/></Relationships>',
        "ppt/slides/slide1.xml": f'<slide><p><t>{phrase}</t></p></slide>',
    })
    write_package(root / "Workbook.xlsx", {
        "xl/workbook.xml": '<workbook xmlns:r="relations"><sheets><sheet name="Data" r:id="data"/></sheets></workbook>',
        "xl/_rels/workbook.xml.rels": '<Relationships><Relationship Id="data" Target="worksheets/sheet1.xml"/></Relationships>',
        "xl/worksheets/sheet1.xml": f'<worksheet><sheetData><row><c r="A1" t="inlineStr"><is><t>{phrase}</t></is></c></row></sheetData></worksheet>',
    })
    (root / "Page.html").write_text(f'<script>fetch("https://invalid.test/network-script-marker")</script><p>{phrase}</p>')
    (root / "Unicode16.txt").write_bytes(phrase.encode("utf-16"))
    (root / "Unicode32.txt").write_bytes(phrase.encode("utf-32"))
    (root / "Letter.rtf").write_text(r"{\rtf1\ansi The \b violet lighthouse\b0 stands on a rocky coast.}")
    (root / "Limited.rtf").write_text(r'{\rtf1\ansi The violet lighthouse stands on a rocky coast.{\header external secret must not appear}{\field{\*\fldinst INCLUDETEXT "https://invalid.test/network-script-marker"}{\fldrslt external secret must not appear}}}')
    (root / "Source.rs").write_text(phrase)  # Recognized code shares the text reader.
    pdf_fixture(root, 2, "Sparse.pdf")
    for name in ["Unsupported-image.png", "Unsupported-audio.wav", "Unsupported-video.mp4"]:
        (root / name).write_bytes(b"not valid media; no searchable text")
    secret = output / "external-secret.txt"
    secret.write_text("external secret must not appear")
    write_package(root / "Unsafe.docx", {"word/document.xml": f'<!DOCTYPE x [<!ENTITY secret SYSTEM "{secret.as_uri()}">]><x><p><t>&secret;</t></p></x>'})

    return run_application_acceptance(args, output, root, exercise,
        "DOCX/ODT/PPTX/XLSX/HTML/RTF and UTF-16/32 literal search, passive XML admission and recognized code text, sparse PDF text-only reads, unsupported media skipping, and unchanged full embedding extraction; literal queries need no installed inference runtime/models; indexed literal text reuse and fresh extraction after a source edit while indexing is paused")


if __name__ == "__main__":
    raise SystemExit(main())
